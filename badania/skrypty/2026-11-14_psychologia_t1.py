print("\n=== B. KOTWICA 52 TYGODNI")
hi=C.rolling(250,min_periods=200).max().shift(1); lo=C.rolling(250,min_periods=200).min().shift(1)
r=C/hi
for N in (10,20):
    ev(first(C>hi,20),N,"nowy szczyt 52t (pierwszy od 20 sesji)")
    ev(first((r>=0.97)&(r<1),10),N,"tuż pod szczytem 52t (do 3%)")
    ev(first(C<lo,20),N,"nowy dołek 52t (pierwszy od 20 sesji)")
    ev(first((C/lo<=1.03)&(C>=lo),10),N,"tuż nad dołkiem 52t (do 3%)")
print(" kwintyle bliskości szczytu 52t (fwd20, przewaga):")
rk=r.where(elig).rank(axis=1,pct=True)
for a,b in ((0,.2),(.2,.4),(.4,.6),(.6,.8),(.8,1.01)): ev((rk>a)&(rk<=b),20,f"  bliskość szczytu kwintyl {a:.1f}-{b:.1f}")
print("\n=== D. LOTERIA (MAX dzienny wzrost z 20 sesji) – decyle, fwd20")
mx=ret.where(~bad).rolling(20).max(); rk=mx.where(elig).rank(axis=1,pct=True)
for a,b in ((0,.1),(.1,.5),(.5,.9),(.9,1.01)): ev((rk>a)&(rk<=b),20,f"  MAX20 percentyl {a:.1f}-{b:.1f}")
ev((rk>.9)&(Cr<3),20,"  MAX20 top10% i cena < 3 zł")
ev((Cr<2),20,"  cena < 2 zł (groszówki)")
atr=(H-L).div(C).rolling(14).mean(); rk=atr.where(elig).rank(axis=1,pct=True)
for a,b in ((0,.2),(.4,.6),(.8,1.01)): ev((rk>a)&(rk<=b),20,f"  zmienność (zakres dzienny) percentyl {a:.1f}-{b:.1f}")
print("\n=== E. EFEKT DYSPOZYCJI – średni koszt zakupu (VWAP 250 sesji)")
tv=(C*V).where(traded); vw=tv.rolling(250,min_periods=150).sum()/V.where(traded).rolling(250,min_periods=150).sum()
g=C/vw-1; rk=g.where(elig).rank(axis=1,pct=True)
for a,b in ((0,.2),(.2,.4),(.4,.6),(.6,.8),(.8,1.01)): ev((rk>a)&(rk<=b),20,f"  zysk/strata posiadaczy kwintyl {a:.1f}-{b:.1f}")
under=(g.rolling(60).min()<-0.20)
for N in (5,10,20):
    ev(first((g>0)&(g.shift(1)<=0)&under,20),N,"powrót 'na zero' po stracie >20% (podaż?)")
    ev(first((g<0)&(g.shift(1)>=0)&(g.rolling(60).max()>0.20),20),N,"zejście pod koszt po zysku >20%")
for N in (5,10): ev(first((g>-0.03)&(g<0)&under&(ret>0),10),N,"tuż pod 'zerem' (do 3%) po stracie >20%")
